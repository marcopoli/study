"""RAGAS evaluation of UniVox on the gold-standard test set.

Answers are generated by the system LLM (configured in system/config.yaml) from the
top-5 retrieved chunks with a context-only prompt. The RAGAS metrics are scored by an
independent LLM judge, Google Gemini 2.5 Flash (temperature 0), so that the model that
generates the answers is not the model that grades them.

Requires GOOGLE_API_KEY (judge) and the API key of the generation provider (e.g., TOGETHER_API_KEY).
Run from the repository root:  python evaluation/scripts/evaluate_ragas.py
"""
import json
import os
import sys
from datetime import datetime

from datasets import Dataset
from ragas import evaluate
from ragas.embeddings import LangchainEmbeddingsWrapper
from ragas.llms import LangchainLLMWrapper
from ragas.metrics import (
    answer_relevancy,
    context_precision,
    context_recall,
    faithfulness,
)
from ragas.run_config import RunConfig
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_google_genai import ChatGoogleGenerativeAI

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
sys.path.append(os.path.join(REPO_ROOT, "system"))

from study_buddy.utils.retriever import HybridRetriever  # noqa: E402
from study_buddy.utils.llm import llm  # noqa: E402  (generation model)
from study_buddy.utils.embeddings import get_embeddings  # noqa: E402  (BAAI/bge-m3)

TEST_SET = os.path.join(REPO_ROOT, "evaluation", "datasets", "test_set.json")
RESULTS_DIR = os.path.join(REPO_ROOT, "evaluation", "results")

JUDGE_MODEL = "gemini-2.5-flash"
JUDGE_TEMPERATURE = 0

# RAGAS execution settings: 16 concurrent workers, up to 10 retries,
# 180 s timeout per call, fixed seed 42; one evaluation pass per item.
RUN_CONFIG = RunConfig(timeout=180, max_retries=10, max_workers=16, seed=42)


def build_judge():
    """Gemini 2.5 Flash as the RAGAS judge (wrapped for RAGAS)."""
    if not os.environ.get("GOOGLE_API_KEY"):
        raise EnvironmentError("GOOGLE_API_KEY is required for the Gemini 2.5 Flash judge.")
    judge = ChatGoogleGenerativeAI(model=JUDGE_MODEL, temperature=JUDGE_TEMPERATURE)
    return LangchainLLMWrapper(judge)


def evaluate_ragas():
    print("Loading test set...")
    with open(TEST_SET, "r", encoding="utf-8") as f:
        test_set = json.load(f)

    print("Initializing HybridRetriever...")
    retriever = HybridRetriever(k=5, fetch_k=20)

    # Context-only generation prompt (system LLM)
    template = """Answer the question based only on the following context:

    {context}

    Question: {question}
    """
    prompt = ChatPromptTemplate.from_template(template)
    chain = prompt | llm | StrOutputParser()

    data = {"question": [], "answer": [], "contexts": [], "ground_truth": []}

    print(f"Running generation on {len(test_set)} questions...")
    for item in test_set:
        question = item["question"]
        docs = retriever.invoke(question)
        contexts = [doc.page_content for doc in docs]
        answer = chain.invoke({"context": "\n\n".join(contexts), "question": question})

        data["question"].append(question)
        data["answer"].append(answer)
        data["contexts"].append(contexts)
        data["ground_truth"].append(item["expected_answer"])

    dataset = Dataset.from_dict(data)

    print(f"Running RAGAS evaluation with judge {JUDGE_MODEL} (temperature {JUDGE_TEMPERATURE})...")
    results = evaluate(
        dataset=dataset,
        metrics=[faithfulness, answer_relevancy, context_precision, context_recall],
        llm=build_judge(),
        embeddings=LangchainEmbeddingsWrapper(get_embeddings()),
        run_config=RUN_CONFIG,
    )
    print(results)

    os.makedirs(RESULTS_DIR, exist_ok=True)
    output_df = results.to_pandas()
    output_df.to_csv(os.path.join(RESULTS_DIR, "ragas_scores.csv"), index=False)

    scores = output_df.mean(numeric_only=True).to_dict()
    with open(os.path.join(RESULTS_DIR, "ragas_summary.json"), "w", encoding="utf-8") as f:
        json.dump({"judge": JUDGE_MODEL, "judge_temperature": JUDGE_TEMPERATURE,
                   "n_items": len(output_df), **scores}, f, indent=4)

    report = f"""# RAGAS Evaluation Report

**Date:** {datetime.now().strftime("%Y-%m-%d")}
**Judge:** {JUDGE_MODEL} (temperature {JUDGE_TEMPERATURE}); single pass per item, seed 42
**Items:** {len(output_df)}

| Metric | Score |
| :--- | :--- |
| Faithfulness | {scores.get('faithfulness', float('nan')):.4f} |
| Answer Relevancy | {scores.get('answer_relevancy', float('nan')):.4f} |
| Context Precision | {scores.get('context_precision', float('nan')):.4f} |
| Context Recall | {scores.get('context_recall', float('nan')):.4f} |
"""
    with open(os.path.join(RESULTS_DIR, "ragas_report.md"), "w", encoding="utf-8") as f:
        f.write(report)
    print(f"Saved item-level scores and summary to {RESULTS_DIR}")


if __name__ == "__main__":
    evaluate_ragas()
